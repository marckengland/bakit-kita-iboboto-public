/**
 * Voting List Export API Route
 *
 * Exports the user's voting list in various formats.
 * Requirements: 17.5, 42.3, 42.4, 42.5
 */

import { NextRequest, NextResponse } from "next/server";
import { cookies } from "next/headers";
import { validateSession } from "@/services/auth.service";
import {
  getVotingListByLevel,
  VotingListByLevel,
  UserListError,
} from "@/services/user-list.service";
import { generateVotingListExport } from "@/services/export.service";

// GET /api/voting-list/export - Export voting list
// Requirement 17.5: Allow users to export or share their voting list
// Requirement 42.3: Allow users to export their voting list with selected politicians' summaries
export async function GET(request: NextRequest) {
  try {
    const cookieStore = await cookies();
    const token = cookieStore.get("auth_token")?.value;

    if (!token) {
      return NextResponse.json({ error: "Unauthorized" }, { status: 401 });
    }

    const session = await validateSession(token);

    const { searchParams } = new URL(request.url);
    const electionYear = searchParams.get("electionYear");
    const format = searchParams.get("format") || "json";

    if (!electionYear) {
      return NextResponse.json({ error: "Election year is required" }, { status: 400 });
    }

    const year = parseInt(electionYear, 10);
    if (isNaN(year)) {
      return NextResponse.json({ error: "Invalid election year" }, { status: 400 });
    }

    // Handle HTML export (printable PDF-style)
    // Requirement 42.3, 42.4, 42.5
    if (format === "html") {
      const result = await generateVotingListExport(session.userId, year, {
        format: "html",
        includeSourceAttribution: true,
        optimizeForPrint: true,
      });

      return new NextResponse(result.content, {
        headers: {
          "Content-Type": result.contentType,
          "Content-Disposition": `attachment; filename="${result.filename}"`,
          "X-Export-Date": result.exportedAt.toISOString(),
        },
      });
    }

    const votingListByLevel = await getVotingListByLevel(session.userId, year);

    switch (format) {
      case "text":
        return exportAsText(votingListByLevel, year);
      case "csv":
        return exportAsCSV(votingListByLevel, year);
      case "json":
      default:
        return NextResponse.json({
          electionYear: year,
          exportedAt: new Date().toISOString(),
          byLevel: votingListByLevel,
        });
    }
  } catch (error) {
    if (error instanceof UserListError) {
      return NextResponse.json({ error: error.message, code: error.code }, { status: 400 });
    }
    console.error("Export voting list error:", error);
    return NextResponse.json({ error: "Failed to export voting list" }, { status: 500 });
  }
}

function exportAsText(byLevel: VotingListByLevel, year: number): NextResponse {
  const levelLabels: Record<string, string> = {
    national: "NATIONAL",
    regional: "REGIONAL",
    provincial: "PROVINCIAL",
    city: "CITY/MUNICIPAL",
    municipal: "MUNICIPAL",
    barangay: "BARANGAY",
  };

  let text = `AKING VOTING LIST - ${year}\n`;
  text += `Exported: ${new Date().toLocaleDateString("fil-PH")}\n`;
  text += "=".repeat(40) + "\n\n";

  for (const [level, items] of Object.entries(byLevel)) {
    if (items.length > 0) {
      text += `${levelLabels[level] || level.toUpperCase()}\n`;
      text += "-".repeat(20) + "\n";
      for (const item of items) {
        const name = item.politician?.fullName || "Unknown";
        text += `• ${item.position}: ${name}\n`;
      }
      text += "\n";
    }
  }

  text += "\n---\n";
  text += "Generated by Bakit Kita Iboboto?\n";
  text += "https://bakitkitaiboboto.ph\n";

  return new NextResponse(text, {
    headers: {
      "Content-Type": "text/plain; charset=utf-8",
      "Content-Disposition": `attachment; filename="voting-list-${year}.txt"`,
    },
  });
}

function exportAsCSV(byLevel: VotingListByLevel, year: number): NextResponse {
  const rows: string[] = ["Level,Position,Politician Name,Added Date"];

  for (const [level, items] of Object.entries(byLevel)) {
    for (const item of items) {
      const name = item.politician?.fullName || "Unknown";
      const addedDate = new Date(item.addedAt).toLocaleDateString("fil-PH");
      // Escape quotes in CSV
      const escapedName = name.includes(",") ? `"${name}"` : name;
      const escapedPosition = item.position.includes(",") ? `"${item.position}"` : item.position;
      rows.push(`${level},${escapedPosition},${escapedName},${addedDate}`);
    }
  }

  const csv = rows.join("\n");

  return new NextResponse(csv, {
    headers: {
      "Content-Type": "text/csv; charset=utf-8",
      "Content-Disposition": `attachment; filename="voting-list-${year}.csv"`,
    },
  });
}
